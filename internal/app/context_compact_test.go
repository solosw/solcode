package app

import (
	"encoding/json"
	"github.com/solosw/solcode/internal/config"
	"net/http"
	"net/http/httptest"
	"sync/atomic"
	"testing"
)

func TestOrganizerSummaryStartupAndSettingsReload(t *testing.T) {
	var mainCalls atomic.Int32
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.URL.Path != "/v1/chat/completions" {
			t.Errorf("unexpected path %s", r.URL.Path)
		}
		var body struct{ Model string }
		if err := json.NewDecoder(r.Body).Decode(&body); err != nil {
			t.Error(err)
		}
		if r.Header.Get("Authorization") != "Bearer "+body.Model+"-key" {
			t.Errorf("wrong credentials for %s", body.Model)
		}
		text := "done"
		if body.Model != "chat" {
			text = "Summary generated by " + body.Model
		} else {
			mainCalls.Add(1)
		}
		w.Header().Set("Content-Type", "application/json")
		_ = json.NewEncoder(w).Encode(map[string]any{"choices": []any{map[string]any{"message": map[string]string{"role": "assistant", "content": text}, "finish_reason": "stop"}}})
	}))
	defer server.Close()
	for _, reloadKind := range []string{"features", "model"} {
		t.Run(reloadKind, func(t *testing.T) {
			cfg := config.Default()
			cfg.WorkDir = t.TempDir()
			cfg.Memory.Enabled, cfg.Session.Enabled, cfg.KnowledgeGraph.Enabled = false, false, false
			cfg.Model, cfg.APIFormat, cfg.APIKey, cfg.BaseURL = "chat", "openai", "chat-key", server.URL
			cfg.MaxContextTokens, cfg.MaxTokens, cfg.SystemPrompt = 12000, 128, "Help with coding."
			cfg.Memory.CompactionTriggerPercent = 80
			cfg.Memory.Organizer = config.OrganizerConfig{Enabled: true, Runtime: "api", Model: "first", APIKey: "first-key", BaseURL: server.URL + "/v1", ContextSize: 131072, MaxOutputTokens: 1024, TimeoutSec: 5}
			disabled := false
			cfg.CodeGraph.Enabled = &disabled
			application, err := New(cfg)
			if err != nil {
				t.Fatal(err)
			}
			defer application.Close()
			reload := application.SwitchModel
			if reloadKind == "features" {
				reload = func(next config.Config) error { return application.ReloadFeatures(next, nil) }
			}
			for _, model := range []string{"first", "second"} {
				if model == "second" {
					cfg.Memory.Organizer.Model, cfg.Memory.Organizer.APIKey = model, model+"-key"
					if err := reload(cfg); err != nil {
						t.Fatal(err)
					}
				}
				got, err := application.sessionSummaryWriter().Summarize(t.Context(), "", "Completed old work.")
				if err != nil || got != "Summary generated by "+model {
					t.Fatalf("summary=%q error=%v", got, err)
				}
			}
			cfg.Memory.Organizer.Enabled = false
			if err := reload(cfg); err != nil {
				t.Fatal(err)
			}
			if application.organizer != nil || application.sessionSummaryWriter() != nil {
				t.Fatal("disabled organizer still active")
			}
			cfg.Memory.Organizer.Enabled = true
			if err := reload(cfg); err != nil {
				t.Fatal(err)
			}
			got, err := application.sessionSummaryWriter().Summarize(t.Context(), "", "Work completed after enabling the API.")
			if err != nil || got != "Summary generated by second" {
				t.Fatalf("enabled summary=%q error=%v", got, err)
			}
		})
	}
}
